CREATE TABLE IF NOT EXISTS settings (id TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS vault (provider TEXT PRIMARY KEY, envelope TEXT NOT NULL, updated_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS owner (id INTEGER PRIMARY KEY CHECK(id=1), uid TEXT NOT NULL UNIQUE, email TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS counters (id TEXT PRIMARY KEY, count INTEGER NOT NULL, expires_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS devices (id TEXT PRIMARY KEY, challenge TEXT NOT NULL, user_code TEXT NOT NULL, expires_at INTEGER NOT NULL, envelope TEXT);
CREATE INDEX IF NOT EXISTS devices_expiry ON devices(expires_at);
